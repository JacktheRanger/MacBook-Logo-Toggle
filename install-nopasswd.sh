#!/bin/zsh -f
# Makes the logo light switch passwordless: installs logo-light.sh as the root-owned
# /usr/local/libexec/logo-light and adds a sudoers rule that lets the current account run it
# without a password, with toggle / on / off / status as the only allowed arguments. The rule names
# the account by its numeric user ID, so no account name can widen it (ALL, or an all-caps name that
# sudoers would read as an alias).
# MacBook Logo Toggle.app detects the rule and switches without showing the admin prompt.
#
# Usage: sudo ./install-nopasswd.sh [install]    install (re-run after editing logo-light.sh to update it)
#        sudo ./install-nopasswd.sh uninstall    remove; the app goes back to asking for a password
# The app bundles this script next to logo-light.sh and runs it from its window as
# "install-nopasswd.sh install|uninstall --user NAME": its admin prompt runs it as root without
# sudo, so there is no SUDO_USER to tell whose account the rule is for.

set -euo pipefail
export PATH=/usr/bin:/bin:/usr/sbin:/sbin

HELPER_DIR=/usr/local/libexec
HELPER=$HELPER_DIR/logo-light
RULE=/etc/sudoers.d/logo-light

# Inside a zsh function $0 is the function's name, so take the script name out here.
SELF=$0
usage() { echo "Usage: sudo $SELF [install|uninstall]" >&2; }

# Anything other than the two known actions is rejected, so a typo such as --uninstall
# can never end up granting the rule instead of removing it.
action=${1:-install}
case $action in
  install | uninstall) ;;
  *) usage; exit 2 ;;
esac

if [[ $EUID -ne 0 ]]; then
  echo "Run it with sudo: sudo $0 $action" >&2
  exit 1
fi
USER_NAME=${SUDO_USER:-}
if (( $# > 1 )); then
  if [[ $2 == --user && $# -eq 3 ]]; then
    USER_NAME=$3
  else
    usage
    exit 2
  fi
fi
if [[ -z $USER_NAME || $USER_NAME == root ]]; then
  echo "Run it with sudo from your own account, not from a root shell." >&2
  exit 1
fi
# Only an existing account with a plain name: the name still goes into a comment line of the rule file.
# It must be the account's own name: id also takes a number as a user ID ("501"), which the sudo -u
# check at the end would reject, after the rule had been written.
if [[ ! $USER_NAME =~ '^[A-Za-z0-9_][A-Za-z0-9_.-]*$' ]] || [[ $(id -un "$USER_NAME" 2>/dev/null) != "$USER_NAME" ]] ||
  ! USER_ID=$(id -u "$USER_NAME" 2>/dev/null); then
  echo "No such account: $USER_NAME" >&2
  exit 1
fi
if [[ $USER_ID == 0 ]]; then
  echo "Run it with sudo from your own account, not from a root shell." >&2
  exit 1
fi

if [[ $action == uninstall ]]; then
  rm -f "$RULE" "$HELPER"
  echo "Removed the passwordless rule and $HELPER; the app will ask for a password again."
  exit 0
fi

# The rule is only safe if the helper and every directory above it can be changed by root alone;
# otherwise another program could replace the helper and use the rule to run anything as root.
# Symlinks are rejected outright (stat describes the link rather than its target, and sudo follows
# it), and so are ACLs (they can grant write access that the mode bits don't show).
check_root_only() {
  local owner mode
  if [[ -L $1 ]]; then
    echo "Unsafe, aborting: $1 is a symlink" >&2
    exit 1
  fi
  owner=$(stat -f %u "$1")
  mode=$(stat -f %Lp "$1")
  if [[ $owner != 0 ]] || (( 8#$mode & 8#022 )); then
    echo "Unsafe, aborting: $1 is writable by someone other than root (owner uid=$owner, mode=$mode)" >&2
    exit 1
  fi
  if [[ -n $(ls -lde "$1" | sed -n '2,$p') ]]; then
    echo "Unsafe, aborting: $1 has an ACL" >&2
    exit 1
  fi
}

for d in / /usr /usr/local; do check_root_only "$d"; done
[[ -e $HELPER_DIR || -L $HELPER_DIR ]] || install -d -o root -g wheel -m 755 "$HELPER_DIR"
check_root_only "$HELPER_DIR"
install -o root -g wheel -m 755 "${0:A:h}/logo-light.sh" "$HELPER"
check_root_only "$HELPER"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by MacBook Logo Toggle's install-nopasswd.sh: switch the Apple logo light without a password"
  echo "# For the account $USER_NAME, named by its user ID (#$USER_ID is a user ID here, not a comment)"
  echo "#$USER_ID ALL=(root) NOPASSWD: $HELPER toggle, $HELPER on, $HELPER off, $HELPER status"
} >"$tmp"
if ! visudo -cf "$tmp" >/dev/null; then
  echo "The sudoers rule failed the syntax check; nothing was installed." >&2
  exit 1
fi
install -o root -g wheel -m 440 "$tmp" "$RULE"

# Check the whole configuration again; if it fails, take the rule back right away so sudo is never left broken.
if ! visudo -c >/dev/null; then
  rm -f "$RULE"
  echo "The full sudoers check failed; the rule was removed again." >&2
  exit 1
fi

# Run the read-only status as you, without a password, to prove the rule works
# (-k ignores the credentials cached by the sudo that started this script).
# Not sudo -l: once any NOPASSWD rule exists it reports every command an admin may run as allowed.
if sudo -u "$USER_NAME" sudo -k -n "$HELPER" status >/dev/null 2>&1; then
  echo "Installed: $USER_NAME can now turn Apple Logo Illumination on or off without a password (Control Center, the app and the command line)."
  echo "Command line: sudo $HELPER status | on | off | toggle"
else
  echo "The rule was written to $RULE, but sudo did not pick it up (/etc/sudoers may not include sudoers.d)." >&2
  exit 1
fi
